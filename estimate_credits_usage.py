#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Оценка расхода кредитов на проверки
"""

# Расписание проверок
CHECKS_PER_DAY = 44  # С 9:00 до 23:20 каждые 20 минут

# Оценка запросов на одну проверку
# (это примерные цифры, реальные могут отличаться)

# 1. Получение списка live матчей (GraphQL запросы)
# Для каждого вида спорта делается отдельный запрос
SPORTS = ["football", "tennis", "basketball", "handball"]  # 4 вида спорта
LIVE_MATCHES_QUERIES = len(SPORTS)  # 4 запроса на проверку

# 2. Получение статистики для матчей
# Анализируется больше матчей, чем отправляется
# Футбол: limit=120 (но реально может быть меньше live матчей)
# Теннис: limit=80
# Баскетбол: limit=120
# Гандбол: limit=80 (но сейчас отключен)

# Примерная оценка: на проверку анализируется ~50-100 матчей
# Но статистика запрашивается только для тех, кто проходит базовые фильтры
# Оценка: ~20-30 матчей проходят базовые фильтры и требуют статистику
STATS_QUERIES_PER_CHECK = 25  # Среднее значение

# 3. Получение коэффициентов
# Коэффициенты запрашиваются только для финальных матчей (max_matches=5)
# Но может быть больше из-за дедупликации
ODDS_QUERIES_PER_CHECK = 5  # Среднее значение

# Итого на одну проверку:
QUERIES_PER_CHECK = LIVE_MATCHES_QUERIES + STATS_QUERIES_PER_CHECK + ODDS_QUERIES_PER_CHECK

print("=" * 70)
print("ОЦЕНКА РАСХОДА КРЕДИТОВ")
print("=" * 70)
print()
print(f"Проверок в день: {CHECKS_PER_DAY}")
print(f"Проверок в неделю: {CHECKS_PER_DAY * 7}")
print(f"Проверок в месяц (30 дней): {CHECKS_PER_DAY * 30}")
print()
print("ЗАПРОСЫ НА ОДНУ ПРОВЕРКУ:")
print(f"  1. Получение списка live матчей: {LIVE_MATCHES_QUERIES} запросов")
print(f"     (по одному на каждый вид спорта: футбол, теннис, баскетбол, гандбол)")
print(f"  2. Получение статистики матчей: ~{STATS_QUERIES_PER_CHECK} запросов")
print(f"     (только для матчей, прошедших базовые фильтры)")
print(f"  3. Получение коэффициентов: ~{ODDS_QUERIES_PER_CHECK} запросов")
print(f"     (только для финальных матчей)")
print()
print(f"ИТОГО запросов на одну проверку: ~{QUERIES_PER_CHECK}")
print()
print("РАСХОД В ДЕНЬ:")
daily_queries = CHECKS_PER_DAY * QUERIES_PER_CHECK
print(f"  Запросов в день: ~{daily_queries}")
print()
print("РАСХОД В НЕДЕЛЮ:")
weekly_queries = CHECKS_PER_DAY * 7 * QUERIES_PER_CHECK
print(f"  Запросов в неделю: ~{weekly_queries}")
print()
print("РАСХОД В МЕСЯЦ (30 дней):")
monthly_queries = CHECKS_PER_DAY * 30 * QUERIES_PER_CHECK
print(f"  Запросов в месяц: ~{monthly_queries}")
print()
print("=" * 70)
print("ПРИМЕЧАНИЯ:")
print("=" * 70)
print("1. Это ОЦЕНОЧНЫЕ цифры. Реальный расход зависит от:")
print("   - Количества live матчей в каждый момент времени")
print("   - Количества матчей, проходящих фильтры")
print("   - Количества финальных матчей для отправки")
print()
print("2. Если матчей нет, расход меньше:")
print("   - Только 4 запроса на получение списков (без статистики)")
print()
print("3. Если матчей много, расход может быть больше:")
print("   - Больше матчей проходит фильтры = больше запросов статистики")
print()
print("4. Оптимизация:")
print("   - Можно кэшировать списки матчей на короткое время")
print("   - Можно уменьшить лимиты анализа (limit)")
print("   - Можно увеличить интервал между проверками")

