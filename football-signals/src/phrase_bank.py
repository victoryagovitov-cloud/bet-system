"""Компактные банки фраз для MAX-постов (дисциплина + дисклеймер).

Идея взята из Backtothestart (improve_telegram_messages), но короче и спокойнее
под тон канала «Честная ставка» — без «братан» и без сотен почти одинаковых строк.
"""

from __future__ import annotations

import random

# Ротация, чтобы канал не выглядел копипастой одной фразы
DISCLAIMERS: list[str] = [
    "Даже сильный анализ — не гарантия. Ставки связаны с риском потери денег.",
    "Мы даём оценку вероятности, решение и ответственность — на вас.",
    "Ставки могут привести к убыткам. Ставьте только то, что готовы потерять.",
    "Это не финансовая рекомендация и не призыв ставить. Играйте осознанно.",
    "Спорт непредсказуем: любая модель ошибается. Берегите банк и голову.",
    "18+. Азартные игры могут вызывать зависимость. При проблемах — остановитесь.",
]

DISCIPLINE_TIPS: list[str] = [
    "Держите размер ставки в пределах рекомендации. Без догонов после минуса.",
    "Проиграли — пауза. Отыгрыш «сразу и больше» чаще добивает банк.",
    "Одна ставка не делает день: важна серия решений и учёт результатов.",
    "Не повышайте долю банка из эмоций. Система важнее азарта.",
    "Лучше пропустить сигнал, чем нарушить лимит риска.",
    "Фиксируйте купоны: так честнее смотреть на реальный результат.",
]

CLOSING_PHRASES: list[str] = [
    "Анализируем честно. Решайте спокойно.",
    "Качество важнее частоты. Берегите банк.",
    "Дисциплина важнее удачи.",
    "Ваше благополучие важнее любой ставки.",
]


def pick_disclaimer(*, rng: random.Random | None = None) -> str:
    r = rng or random
    return r.choice(DISCLAIMERS)


def pick_discipline(*, rng: random.Random | None = None) -> str:
    r = rng or random
    return r.choice(DISCIPLINE_TIPS)


def pick_closing(*, rng: random.Random | None = None) -> str:
    r = rng or random
    return r.choice(CLOSING_PHRASES)


def format_footer(*, rng: random.Random | None = None) -> str:
    """Подвал каждого поста: дисциплина → закрытие → дисклеймер."""
    return (
        f"{pick_discipline(rng=rng)}\n"
        f"{pick_closing(rng=rng)}\n"
        f"⚠️ {pick_disclaimer(rng=rng)}"
    )
